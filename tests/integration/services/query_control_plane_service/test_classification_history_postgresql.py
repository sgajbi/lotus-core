def migration(connection):
    root = next(
        parent
        for parent in Path(__file__).resolve().parents
        if (parent / "pyproject.toml").is_file()
    )
    path = root / "alembic/versions"
    module = runpy.run_path(str(path / "c183b2c3d544_instrument_classification_history.py"))
    assert module["revision"] == "c183b2c3d544"
    module["upgrade"].__globals__["op"] = Operations(MigrationContext.configure(connection))
    return module


