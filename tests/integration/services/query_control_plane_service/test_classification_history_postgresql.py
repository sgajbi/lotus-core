def headers(*, write=False):
    result = {
        "X-Actor-Id": "synthetic-operator",
        "X-Tenant-Id": "synthetic-reference",
        "X-Role": "ops",
        "X-Correlation-Id": "synthetic-correlation",
        "X-Service-Identity": "synthetic-source",
        "X-Capabilities": (
            "ingestion.reference_data.write"
            if write
            else "source_data.instrument_reference_bundle.read"
        ),
        "X-Enterprise-Auth-Key-Id": "synthetic-key",
        "X-Enterprise-Auth-Timestamp": str(int(time())),
    }
    result["X-Enterprise-Auth-Signature"] = _enterprise_auth_context_signature(
        _normalize_headers(result), "synthetic-context-secret"
    )
    if write:
        result["X-Idempotency-Key"] = uuid4().hex
    return result


async def read_history(client, cut, **changes):
    selected = selection(cut, **changes)
    response = await client.post(
        READ_PATH,
        headers=headers(),
        json={
            "as_of_date": selected.period_end.isoformat(),
            "history_selection": selected.model_dump(mode="json"),
        },
    )
    assert response.status_code == 200, response.text
    return response.json()


async def test_registered_handlers_preserve_original_correction_and_refusals(
    classification_sessions,
):
    original = source_cut()
    cut_a = retained_cut(original)
    rows = [row.model_dump(mode="json") for row in original.assignments]
    rows[0]["effective_to"] = "2026-01-16"
    rows.append(
        rows[0]
        | {
            "effective_from": "2026-01-16",
            "effective_to": "2026-02-01",
            "group_id": "FINANCE",
            "source_record_id": "SYNTHETIC_RECLASS",
        }
    )
    corrected = source_cut(source_version=2, predecessor_cut_id=cut_a.cut_id, assignments=rows)
    cut_b = retained_cut(corrected)
    async with (
        httpx.AsyncClient(
            transport=httpx.ASGITransport(app=write_app), base_url="http://test"
        ) as writer,
        httpx.AsyncClient(
            transport=httpx.ASGITransport(app=read_app), base_url="http://test"
        ) as reader,
    ):
        for source in (original, corrected):
            response = await writer.post(
                WRITE_PATH,
                headers=headers(write=True),
                json={
                    "assignment_cut": source.model_dump(mode="json"),
                },
            )
            assert response.status_code == 202, response.text
        first = await read_history(reader, cut_a)
        second = await read_history(reader, cut_b)
        assert first["history"]["status"] == second["history"]["status"] == "COMPLETE"
        assert first["history"]["assignments"] == original.model_dump(mode="json")["assignments"]
        assert len(second["history"]["assignments"]) == 3
        assert first["source_evidence_current"] is False
        assert first["history"]["compatibility"] == "UNAVAILABLE"
        assert first["records"] == []
        replay = await read_history(reader, cut_a)
        assert replay["history"] == first["history"]
        assert replay["content_hash"] == first["content_hash"]
        for changes in (
            {"producer_id": "FOREIGN"},
            {"classification_set_id": "FOREIGN"},
            {"source_version": 99},
            {"cut_id": "sha256:" + "0" * 64},
            {"content_hash": "sha256:" + "0" * 64},
            {"known_at": "2026-02-01T00:00:00Z"},
            {"source_as_of": "2026-01-31T00:00:00Z"},
            {"expected_security_ids": ["SYNTHETIC_A"]},
        ):
            refused = await read_history(reader, cut_a, **changes)
            assert refused["history"]["status"] == "UNAVAILABLE"
            assert refused["history"]["assignments"] == []
        conflict = source_cut(assignments=[rows[1]])
        response = await writer.post(
            WRITE_PATH,
            headers=headers(write=True),
            json={
                "assignment_cut": conflict.model_dump(mode="json"),
            },
        )
        assert response.status_code == 409, response.text
        partial = source_cut(source_record_id="SYNTHETIC_PARTIAL", assignments=[rows[1]])
        response = await writer.post(
            WRITE_PATH,
            headers=headers(write=True),
            json={
                "assignment_cut": partial.model_dump(mode="json"),
            },
        )
        assert response.status_code == 202, response.text
        missing = await read_history(reader, retained_cut(partial))
        assert missing["history"]["status"] == "PARTIAL"
        assert missing["history"]["missing_security_ids"] == ["SYNTHETIC_A"]


async def test_append_race_replay_and_immutable_database_guards(classification_sessions):
    from src.services.ingestion_service.app.services.classification_history_writer import (
        ClassificationHistoryWriter,
    )

    async def append(source):
        async with classification_sessions.begin() as session:
            return await ClassificationHistoryWriter(session).append(source)

    results = await asyncio.gather(append(source_cut()), append(source_cut()))
    assert results[0] == results[1]
    original = results[0]
    corrected_rows = [row.model_dump(mode="json") for row in original.source.assignments]
    corrected_rows[0]["group_id"] = "FINANCE"
    corrections = (
        source_cut(source_version=2, predecessor_cut_id=original.cut_id),
        source_cut(
            source_version=2, predecessor_cut_id=original.cut_id, assignments=corrected_rows
        ),
    )
    competing = await asyncio.gather(
        *(append(source) for source in corrections), return_exceptions=True
    )
    assert sum(isinstance(result, ClassificationHistoryConflict) for result in competing) == 1
    assert await append(source_cut()) == original
    for changes in (
        {"source_version": 3, "predecessor_cut_id": original.cut_id},
        {"source_version": 2, "predecessor_cut_id": original.cut_id, "producer_id": "FOREIGN"},
        {"generated_at": "2099-01-01T00:00:00Z", "source_record_id": "SYNTHETIC_FUTURE"},
    ):
        with pytest.raises(ClassificationHistoryConflict):
            await append(source_cut(**changes))
    for statement in (
        f"UPDATE {TABLE} SET received_at=now()",
        f"DELETE FROM {TABLE}",
        f"TRUNCATE {TABLE}",
    ):
        async with classification_sessions() as session:
            with pytest.raises(DBAPIError, match="CLASSIFICATION_CUT_IMMUTABLE"):
                await session.execute(text(statement))
            await session.rollback()
    async with classification_sessions() as session:
        assert await session.scalar(text(f"SELECT count(*) FROM {TABLE}")) == 2


